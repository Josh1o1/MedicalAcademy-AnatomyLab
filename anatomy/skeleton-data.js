function sideLabel(key) {
    if (key.endsWith(".l")) return "Left";
    if (key.endsWith(".r")) return "Right";
    return "";
}

function prettyName(key) {
    return formatSkeletonName(key);
}

export function formatSkeletonName(key) {
    if (!key) return "Anatomical Structure";

    let name = key;

    // Convert GLB underscores to readable spaces.
    name = name.replace(/_/g, " ");

    // Detect the model's compact side suffixes.
    let side = "";

    if (/handr$/i.test(name)) {
        side = "Right Hand";
        name = name.replace(/handr$/i, "").trim();
    } else if (/handl$/i.test(name)) {
        side = "Left Hand";
        name = name.replace(/handl$/i, "").trim();
    } else if (/footr$/i.test(name)) {
        side = "Right Foot";
        name = name.replace(/footr$/i, "").trim();
    } else if (/footl$/i.test(name)) {
        side = "Left Foot";
        name = name.replace(/footl$/i, "").trim();
    } else if (/\\.r$/i.test(name)) {
        side = "Right";
        name = name.replace(/\\.r$/i, "").trim();
    } else if (/\\.l$/i.test(name)) {
        side = "Left";
        name = name.replace(/\\.l$/i, "").trim();
    }

    // Make anatomical model names readable.
    name = name.replace(/\\s+/g, " ").trim();

    name = name
        .replace(/\\bfirst\\b/gi, "First")
        .replace(/\\bsecond\\b/gi, "Second")
        .replace(/\\bthird\\b/gi, "Third")
        .replace(/\\bfourth\\b/gi, "Fourth")
        .replace(/\\bfifth\\b/gi, "Fifth")
        .replace(/\\bsixth\\b/gi, "Sixth")
        .replace(/\\bseventh\\b/gi, "Seventh")
        .replace(/\\beighth\\b/gi, "Eighth")
        .replace(/\\bninth\\b/gi, "Ninth")
        .replace(/\\btenth\\b/gi, "Tenth")
        .replace(/\\beleventh\\b/gi, "Eleventh")
        .replace(/\\btwelfth\\b/gi, "Twelfth");

    name = name.replace(/\\b(\\w)/g, (match) => match.toUpperCase());

    return side ? `${name} — ${side}` : name;
}

